"""DRI-6 world generator: imperfect lookups.

Base worlds are DRI-4's five families with a complete lineage record: nothing missing
and nothing spurious, generated by the frozen DRI-4 generator. The record, the truth
and the true grouping are unchanged. Only what a lookup reports changes.

Each lookup call reports a grouping with errors:

- **split rate e_s:** each true unit with more than one observation is, with
  probability e_s, reported as one unit per observation. The lookup misses a
  dependence, which is the direction that makes false settlements.
- **merge rate e_m:** each pair of true units is, with probability e_m, reported as
  one unit. The lookup invents a dependence.
- **both:** a unit merged with another is reported merged, not split.

Every call draws its errors afresh, independently of earlier calls. Random numbers
are common across arms and cells: call k on a decision uses a stream seeded by
`salt|lookup|decision|k`, which draws one number per unit and one per pair of units
whatever the rates.
"""

from __future__ import annotations

import hashlib
import random
from collections import defaultdict
from collections.abc import Iterable, Mapping
from typing import Any

from experiments.dri3.world import Decision, World
from experiments.dri4.world import base_world

FAMILIES = (
    "joint_domain",
    "separate_control_shared_origin",
    "three_stacked",
    "decoy_shared_identity",
    "side_asymmetric_trap",
)


def _seed(*parts: object) -> int:
    return int.from_bytes(hashlib.sha256("|".join(map(str, parts)).encode()).digest(), "big")


def reported_units(
    decision: Decision, split: float, merge: float, rng: random.Random
) -> tuple[tuple[str, str], ...]:
    members: dict[str, list[str]] = defaultdict(list)
    for observation, unit in decision.units:
        members[unit].append(observation)
    units = sorted(members)
    split_draw = {unit: rng.random() for unit in units}
    parent = {unit: unit for unit in units}

    def find(unit: str) -> str:
        while parent[unit] != unit:
            unit = parent[unit]
        return unit

    for index, a in enumerate(units):
        for b in units[index + 1:]:
            if rng.random() < merge:
                ra, rb = find(a), find(b)
                if ra != rb:
                    parent[max(ra, rb)] = min(ra, rb)
    group_size = defaultdict(int)
    for unit in units:
        group_size[find(unit)] += 1
    label: dict[str, str] = {}
    for unit in units:
        root = find(unit)
        for observation in members[unit]:
            if group_size[root] > 1:
                label[observation] = f"merged:{root}"
            elif len(members[unit]) > 1 and split_draw[unit] < split:
                label[observation] = f"{unit}~{observation}"
            else:
                label[observation] = unit
    return tuple((observation, label[observation]) for observation, _ in decision.units)


class ImperfectLook:
    """The lineage lookup for one decision under one error cell. Every call is counted."""

    def __init__(self, decision: Decision, salt: str, split: float, merge: float) -> None:
        self._decision = decision
        self._salt = salt
        self._split = split
        self._merge = merge
        self.calls = 0

    def __call__(self) -> tuple[tuple[str, str], ...] | None:
        call = self.calls
        self.calls += 1
        if not self._decision.lookup_available:
            return None
        rng = random.Random(_seed(self._salt, "lookup", self._decision.decision_id, call))
        return reported_units(self._decision, self._split, self._merge, rng)


def cells(config: Mapping[str, Any]) -> tuple[tuple[float, float], ...]:
    return tuple((float(split), float(merge)) for split, merge in config["lookup_error_cells"])


def cell_key(split: float, merge: float) -> str:
    return f"split={split}|merge={merge}"


def parse_cell(cell: str) -> tuple[float, float]:
    split, merge = (float(part.split("=")[1]) for part in cell.split("|"))
    return split, merge


def iter_worlds(
    config: Mapping[str, Any], salt: str, worlds_per_family: int | None = None
) -> Iterable[World]:
    count = config["worlds_per_family"] if worlds_per_family is None else worlds_per_family
    for family in config["families"]:
        for replicate in range(count):
            yield base_world(config, salt, family, replicate)
